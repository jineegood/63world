import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const moduleOutput = path.join(root, 'supabase/functions/_shared/generated-quest-catalog-v3.mjs');
const sqlOutput = path.join(root, 'supabase/generated/quest-catalog-v3.sql');
const migrationPath = path.join(
  root,
  'supabase/migrations/202607260005_server_authoritative_quests_v3.sql',
);
const context = vm.createContext({ window:{} });
vm.runInContext(fs.readFileSync(path.join(root, 'src/quest-data.js'), 'utf8'), context);

const { QUEST_DEFS, QUEST_ORDER } = context.window.YuksamQuestData;
const events = Object.freeze({
  tut_equip:{ kind:'action', target:'equip' },
  tut_healing_well:{ kind:'healing', target:'well' },
  mushroom_hunt:{ kind:'monster', target:'forest_mushroom' },
  tut_shop:{ kind:'action', target:'buy' },
  tut_skill:{ kind:'action', target:'learnSkill' },
  slime_hunt:{ kind:'monster', target:'forest_slime' },
  tut_costume:{ kind:'questGift', target:'cs_questSproutRibbon' },
  tut_accessory:{ kind:'action', target:'buyAccessory' },
  elite_slime_hunt:{ kind:'monster', target:'forest_elite_slime' },
  tut_enhance:{ kind:'action', target:'enhance' },
  stomp_hunt:{ kind:'monster', target:'desert_stomp' },
  snake_hunt:{ kind:'monster', target:'desert_snake' },
  tut_pet:{ kind:'action', target:'pet' },
  elite_snake_hunt:{ kind:'monster', target:'desert_elite_snake' },
  swamp_spider_hunt:{ kind:'monster', target:'swamp_tarantula' },
  swamp_zombie_hunt:{ kind:'monster', target:'swamp_zombie' },
  swamp_king_hunt:{ kind:'monster', target:'swamp_elite_zombie' },
});

const amount = (value) => Math.max(0, Number(value) || 0);
const item = (value) => typeof value === 'string' && value ? value : null;
const catalog = Object.freeze(Object.fromEntries(QUEST_ORDER.map((questId, index) => {
  const def = QUEST_DEFS[questId];
  const event = events[questId];
  if (!def || !event) throw new Error(`missing authoritative quest mapping: ${questId}`);
  return [questId, {
    sequence:index + 1,
    target:amount(def.target),
    event,
    reward:{
      exp:amount(def.reward?.exp),
      gold:amount(def.reward?.gold),
      building:amount(def.reward?.building),
      item:item(def.reward?.item),
    },
    grantOnAccept:{
      gold:amount(def.grantOnAccept?.gold),
      building:amount(def.grantOnAccept?.building),
      item:item(def.grantOnAccept?.item),
    },
  }];
})));

const js = [
  '// Generated by tools/generate-quest-catalog-v3.mjs. Do not edit.',
  `export const QUEST_ORDER_V3 = Object.freeze(${JSON.stringify(QUEST_ORDER, null, 2)});`,
  `export const QUEST_CATALOG_V3 = Object.freeze(${JSON.stringify(catalog, null, 2)});`,
  '',
].join('\n\n');

const quote = (value) => value === null
  ? 'null'
  : `'${String(value).replaceAll("'", "''")}'`;
const rows = QUEST_ORDER.map((questId) => {
  const quest = catalog[questId];
  return `(${[
    quote(questId),
    quest.sequence,
    quote(quest.event.kind),
    quote(quest.event.target),
    quest.target,
    quest.reward.exp,
    quest.reward.gold,
    quest.reward.building,
    quote(quest.reward.item),
    quest.grantOnAccept.gold,
    quest.grantOnAccept.building,
    quote(quest.grantOnAccept.item),
  ].join(',')})`;
});
const sql = [
  '-- Generated by tools/generate-quest-catalog-v3.mjs. Do not edit.',
  `-- quests: ${rows.length}`,
  '',
  'insert into public.game_quest_catalog_v3',
  '  (quest_id, sequence_number, event_kind, event_target, target_count,',
  '   reward_exp, reward_gold, reward_building, reward_item_id,',
  '   accept_gold, accept_building, accept_item_id)',
  'values',
  `${rows.join(',\n')}\non conflict (quest_id) do update set`,
  '  sequence_number = excluded.sequence_number, event_kind = excluded.event_kind,',
  '  event_target = excluded.event_target, target_count = excluded.target_count,',
  '  reward_exp = excluded.reward_exp, reward_gold = excluded.reward_gold,',
  '  reward_building = excluded.reward_building, reward_item_id = excluded.reward_item_id,',
  '  accept_gold = excluded.accept_gold, accept_building = excluded.accept_building,',
  '  accept_item_id = excluded.accept_item_id;',
  '',
].join('\n');

const outputs = [[moduleOutput, js], [sqlOutput, sql]];
const beginMarker = '-- BEGIN GENERATED QUEST CATALOG V3';
const endMarker = '-- END GENERATED QUEST CATALOG V3';
const migrationSource = fs.readFileSync(migrationPath, 'utf8');
const renderMigration = (source) => {
  const begin = source.indexOf(beginMarker);
  const end = source.indexOf(endMarker);
  if (begin < 0 || end < begin) throw new Error('quest catalog migration markers are missing');
  return `${source.slice(0, begin + beginMarker.length)}\n${sql.trimEnd()}\n${source.slice(end)}`;
};
const expectedMigration = renderMigration(migrationSource);
if (process.argv.includes('--check')) {
  const stale = outputs.some(([file, expected]) => (
    !fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== expected
  )) || migrationSource !== expectedMigration;
  if (stale) {
    console.error('quest catalog is missing or stale; run node tools/generate-quest-catalog-v3.mjs');
    process.exit(1);
  }
} else {
  for (const [file, source] of outputs) {
    fs.mkdirSync(path.dirname(file), { recursive:true });
    fs.writeFileSync(file, source, 'utf8');
  }
  fs.writeFileSync(migrationPath, expectedMigration, 'utf8');
}
