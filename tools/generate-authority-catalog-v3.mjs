import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outputPath = path.join(root, 'supabase/generated/authority-catalog-v3.sql');
const migrationPath = path.join(
  root,
  'supabase/migrations/202607260003_server_authoritative_economy_v3.sql',
);
const context = vm.createContext({ window:{} });

for (const relative of ['src/core-utils.js', 'src/game-data.js']) {
  vm.runInContext(fs.readFileSync(path.join(root, relative), 'utf8'), context);
}
const baseItems = Object.values(context.window.YuksamData.ITEM_DEFS);
vm.runInContext(fs.readFileSync(path.join(root, 'src/costume-data.js'), 'utf8'), context);
const costumes = Object.values(context.window.COSTUME_DEFS_V55);
const skills = Object.values(context.window.YuksamData.V24_SKILLS);

const quote = (value) => value === null || value === undefined
  ? 'null'
  : `'${String(value).replaceAll("'", "''")}'`;
const bool = (value) => value ? 'true' : 'false';
const integer = (value, fallback = 0) => Number.isSafeInteger(Number(value))
  ? Number(value)
  : fallback;
const itemRow = (item, kind) => {
  const currency = Number(item.buildingPrice) > 0
    ? 'building'
    : Number(item.price) > 0 ? 'gold' : 'none';
  const price = currency === 'building' ? integer(item.buildingPrice) : integer(item.price);
  return `(${[
    quote(item.id),
    quote(kind),
    quote(currency),
    price,
    quote(item.slot),
    quote(item.classOnly || null),
    integer(item.levelReq, 1) || 1,
    bool(item.questOnly || item.questReward),
  ].join(',')})`;
};
const unlockLevel = (skill) => {
  const line = integer(skill.line, 1) || 1;
  return line <= 4 ? 1 : line <= 6 ? 5 : line <= 8 ? 7 : 9;
};
const prerequisites = (skill) => ({
  all:Array.isArray(skill.prereq) ? skill.prereq : [],
  ranks:skill.prereqPoints || {},
  any:Array.isArray(skill.prereqAny) ? skill.prereqAny : [],
  total:skill.prereqTotal || null,
});
const jsonSql = (value) => `${quote(JSON.stringify(value))}::jsonb`;
const skillRow = (skill) => `(${[
  quote(skill.id),
  quote(skill.classOnly),
  quote(skill.specOnly || null),
  unlockLevel(skill),
  integer(skill.maxPoints, 1) || 1,
  integer(skill.cost, 1) || 1,
  jsonSql(prerequisites(skill)),
].join(',')})`;

const specs = [
  ['warrior', '방어'], ['warrior', '무기'],
  ['mage', '냉기'], ['mage', '화염'],
  ['priest', '신성'], ['priest', '암흑'],
];
const sorted = (rows) => [...rows].sort((a, b) => String(a.id).localeCompare(String(b.id)));
const sql = [
  '-- Generated by tools/generate-authority-catalog-v3.mjs. Do not edit.',
  `-- base-items: ${baseItems.length}`,
  `-- costumes: ${costumes.length}`,
  `-- total-items: ${baseItems.length + costumes.length}`,
  `-- skills: ${skills.length}`,
  '',
  'insert into public.game_item_catalog_v3',
  '  (item_id, inventory_kind, currency_kind, price, slot, class_name, level_required, quest_only)',
  'values',
  [...sorted(baseItems).map((item) => itemRow(item, 'gear')),
    ...sorted(costumes).map((item) => itemRow(item, 'costume'))].join(',\n') +
    '\non conflict (item_id) do update set',
  '  inventory_kind = excluded.inventory_kind, currency_kind = excluded.currency_kind,',
  '  price = excluded.price, slot = excluded.slot, class_name = excluded.class_name,',
  '  level_required = excluded.level_required, quest_only = excluded.quest_only;',
  '',
  'insert into public.game_skill_catalog_v3',
  '  (skill_id, class_name, spec_name, unlock_level, max_rank, point_cost, prerequisites)',
  'values',
  sorted(skills).map(skillRow).join(',\n') + '\non conflict (skill_id) do update set',
  '  class_name = excluded.class_name, spec_name = excluded.spec_name,',
  '  unlock_level = excluded.unlock_level, max_rank = excluded.max_rank,',
  '  point_cost = excluded.point_cost, prerequisites = excluded.prerequisites;',
  '',
  'insert into public.game_specialization_catalog_v3(class_name, spec_name) values',
  specs.map(([klass, spec]) => `(${quote(klass)},${quote(spec)})`).join(',\n') +
    '\non conflict (class_name, spec_name) do nothing;',
  '',
].join('\n');

const beginMarker = '-- BEGIN GENERATED AUTHORITY CATALOG V3';
const endMarker = '-- END GENERATED AUTHORITY CATALOG V3';
const renderMigration = (source) => {
  const begin = source.indexOf(beginMarker);
  const end = source.indexOf(endMarker);
  if (begin < 0 || end < begin) throw new Error('authority catalog migration markers are missing');
  const afterEnd = end + endMarker.length;
  return `${source.slice(0, begin + beginMarker.length)}\n${sql.trimEnd()}\n${endMarker}${source.slice(afterEnd)}`;
};
const migrationSource = fs.readFileSync(migrationPath, 'utf8');
const expectedMigration = renderMigration(migrationSource);

if (process.argv.includes('--check')) {
  if (!fs.existsSync(outputPath)
    || fs.readFileSync(outputPath, 'utf8') !== sql
    || migrationSource !== expectedMigration) {
    console.error('authority catalog is missing or stale; run node tools/generate-authority-catalog-v3.mjs');
    process.exit(1);
  }
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive:true });
  fs.writeFileSync(outputPath, sql, 'utf8');
  fs.writeFileSync(migrationPath, expectedMigration, 'utf8');
}
