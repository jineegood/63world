import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';

const root = path.resolve(import.meta.dirname, '..');
const outputPath = path.join(root, 'supabase/functions/_shared/pvp-catalog.mjs');
const fields = [
  'id', 'name', 'classOnly', 'specOnly', 'line', 'maxPoints', 'active',
  'bonuses', 'flatBonuses',
  'guardShieldPct', 'armorBonusPct', 'cleanseChance', 'reviveHealPct',
  'reviveCooldown', 'reflectPct', 'doubleAttackPct', 'executeHp',
  'activeStunChance', 'critChanceBonus', 'critDmgBonus', 'monsterMissChance',
  'healBoost', 'shadowLifestealChance', 'shadowCritChance',
];

function stable(value) {
  if (Array.isArray(value)) return value.map(stable);
  if (!value || typeof value !== 'object') return value;
  return Object.fromEntries(Object.keys(value).sort().map((key) => [key, stable(value[key])]));
}

const window = {};
const context = { window, crypto:{ randomUUID:() => 'catalog' } };
vm.runInNewContext(fs.readFileSync(path.join(root, 'src/core-utils.js'), 'utf8'), context);
vm.runInNewContext(fs.readFileSync(path.join(root, 'src/game-data.js'), 'utf8'), context);
vm.runInNewContext(fs.readFileSync(path.join(root, 'src/patch-data.js'), 'utf8'), context);

const catalog = {};
for (const [id, skill] of Object.entries(window.YuksamData.V24_SKILLS || {})) {
  const kept = {};
  for (const field of fields) {
    if (skill[field] !== undefined) kept[field] = stable(skill[field]);
  }
  catalog[id] = stable(kept);
}
const data = window.YuksamData;
const patchData = window.YuksamPatchData;
const trainingItems = {
  training_greatsword:{ id:'training_greatsword', slot:'weapon', classOnly:'warrior', stats:{ 힘:1 } },
  training_staff:{ id:'training_staff', slot:'weapon', classOnly:'mage', stats:{ 지능:1 } },
  training_book:{ id:'training_book', slot:'weapon', classOnly:'priest', stats:{ 정신:1 } },
};
const itemFields = ['id', 'slot', 'classOnly', 'levelReq', 'stats', 'possessStats'];
const items = {};
for (const [id, item] of Object.entries({ ...data.ITEM_DEFS, ...trainingItems })) {
  items[id] = {};
  for (const field of itemFields) {
    if (item[field] !== undefined) items[id][field] = stable(item[field]);
  }
}
const profileCatalog = stable({
  classes:Object.fromEntries(Object.keys(data.CLASS_META).map((className) => [
    className,
    {
      baseStats:data.resolvePlayerBaseStats(className, 2),
      legacyVitality:data.resolvePlayerBaseStats(className, 0).체력,
      defaultWeapon:{
        warrior:'training_greatsword',
        mage:'training_staff',
        priest:'training_book',
      }[className],
    },
  ])),
  items,
  pets:Object.fromEntries(Object.entries(patchData.PET_DEFS_V27 || {})
    .map(([id, pet]) => [id, { id, stats:stable(pet.stats || {}) }])),
  xpRequirements:data.XP_REQUIREMENTS,
});
const source = `// Generated by tools/build-pvp-catalog.mjs. Do not edit by hand.\n`
  + `export const PVP_SKILLS = Object.freeze(${JSON.stringify(stable(catalog), null, 2)});\n`
  + `export const PVP_PROFILE_CATALOG = Object.freeze(${JSON.stringify(profileCatalog, null, 2)});\n`;

if (process.argv.includes('--check')) {
  const current = fs.existsSync(outputPath) ? fs.readFileSync(outputPath, 'utf8') : '';
  if (current !== source) {
    process.stderr.write('PvP skill catalog is stale. Run: node tools/build-pvp-catalog.mjs\n');
    process.exit(1);
  }
} else {
  fs.mkdirSync(path.dirname(outputPath), { recursive:true });
  fs.writeFileSync(outputPath, source);
}
