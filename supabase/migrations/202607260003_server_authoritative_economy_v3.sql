    when 0 then 0.80 when 1 then 0.60 when 2 then 0.40 when 3 then 0.20
    else 0
  end;
  v_success := pg_catalog.random() < v_chance;
  v_new_tier := case when v_success then v_current_tier + 1
    else greatest(0, v_current_tier - 1) end;
