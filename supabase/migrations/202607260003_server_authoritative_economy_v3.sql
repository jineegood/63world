create or replace function public.private_build_student_snapshot_v3(
  p_user_id uuid
)
returns jsonb
language sql
stable
security definer
set search_path = ''
as $$
  select case
    when base.snapshot is null then null
    else jsonb_set(
      base.snapshot,
      '{inventory}',
      coalesce((
        select jsonb_agg(jsonb_build_object(
          'id', i.id,
          'item_definition_id', i.item_definition_id,
          'inventory_kind', i.inventory_kind,
          'enhancement_tier', i.enhancement_tier,
          'equipped_slot', i.equipped_slot
        ) order by i.inventory_kind, i.item_definition_id, i.id)
        from public.player_inventory_v3 as i
        where i.user_id = p_user_id
      ), '[]'::jsonb)
    )
  end
  from (
    select public.private_build_student_snapshot_v3_phase1(p_user_id) as snapshot
  ) as base;
$$;

