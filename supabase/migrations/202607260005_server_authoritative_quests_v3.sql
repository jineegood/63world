  if v_core.revision <> p_expected_revision then raise exception using message='PLAYER_REVISION_CONFLICT'; end if;
  v_question:=public.private_pick_combat_question_v3('forest');
  v_safe:=(v_question-'answerKey')||jsonb_build_object('questionToken',v_token);
  insert into public.player_healing_sessions_v3(user_id,question_token,safe_question,expires_at)
  values(p_user_id,v_token,v_safe,now()+interval '5 minutes')
  on conflict(user_id) do update set question_token=v_token,safe_question=v_safe,
    expires_at=excluded.expires_at,created_at=now();
  insert into public.player_healing_question_secrets_v3(user_id,question_token,answer_key)
  values(p_user_id,v_token,v_question->>'answerKey')
  on conflict(user_id) do update set question_token=v_token,answer_key=excluded.answer_key;
  v_response:=jsonb_build_object('ok',true,'question',v_safe);
  return public.private_store_service_receipt_v3(
    p_user_id,v_request_id,'private_start_student_healing_v3',v_response
  );
end;
$$;
create or replace function public.private_submit_student_healing_v3(
  p_user_id uuid,
  p_question_token uuid,
  p_answer text,
  p_expected_revision bigint,
  p_request_id text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_session public.player_healing_sessions_v3%rowtype;
  v_answer text;
  v_correct boolean;
  v_request_id uuid;
  v_receipt jsonb;
  v_response jsonb;
begin
  perform public.private_require_service_role_v3();
  if p_request_id is null or p_request_id !~* '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-5][0-9a-fA-F]{3}-[89ab][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$' then
    raise exception using message='INVALID_REQUEST';
  end if;
  v_request_id:=p_request_id::uuid;
  perform pg_catalog.pg_advisory_xact_lock(
    pg_catalog.hashtextextended(p_user_id::text||':'||v_request_id::text,0)
  );
  v_receipt:=public.private_read_service_receipt_v3(
    p_user_id,v_request_id,'private_submit_student_healing_v3'
  );
  if v_receipt is not null then return v_receipt; end if;
  select * into v_session from public.player_healing_sessions_v3
  where user_id=p_user_id for update;
  select answer_key into v_answer from public.player_healing_question_secrets_v3
  where user_id=p_user_id and question_token=p_question_token;
  if v_session.user_id is null or v_session.question_token<>p_question_token
    or v_session.expires_at<=now() or v_answer is null then
    raise exception using message='HEALING_NOT_ACTIVE';
  end if;
  v_correct:=public.private_normalize_combat_answer_v3(p_answer)
    =public.private_normalize_combat_answer_v3(v_answer);
  delete from public.player_healing_sessions_v3 where user_id=p_user_id;
  if v_correct then
    update public.player_core_v3 set current_hp=max_hp,revision=revision+1,updated_at=now()
    where user_id=p_user_id and revision=p_expected_revision;
    if not found then raise exception using message='PLAYER_REVISION_CONFLICT'; end if;
    perform public.private_progress_student_quest_v3(p_user_id,'healing','well');
  end if;
  v_response:=jsonb_build_object('ok',true,'correct',v_correct,
    'player',public.private_build_student_snapshot_v3(p_user_id));
  return public.private_store_service_receipt_v3(
    p_user_id,v_request_id,'private_submit_student_healing_v3',v_response
  );
end;
