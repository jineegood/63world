create or replace function public.private_progress_student_quest_v3(
  p_user_id uuid,
  p_event_kind text,
  p_event_target text
)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_count integer := 0;
begin
  update public.player_quests_v3 as q
  set progress = least(c.target_count, q.progress + 1),
      status = case when q.progress + 1 >= c.target_count then 'ready' else 'active' end,
      completed_at = case when q.progress + 1 >= c.target_count then coalesce(q.completed_at, now()) else q.completed_at end,
      updated_at = now()
  from public.game_quest_catalog_v3 as c
  where q.user_id = p_user_id
    and q.quest_id = c.quest_id
    and q.status = 'active'
    and c.event_kind = p_event_kind
    and c.event_target = p_event_target;
  get diagnostics v_count = row_count;
  return v_count > 0;
end;
$$;
create or replace function public.accept_student_quest_v3(
  p_quest_id text,
  p_expected_revision bigint,
  p_request_id text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_request_id uuid;
  v_receipt jsonb;
  v_response jsonb;
  v_core public.player_core_v3%rowtype;
  v_quest public.game_quest_catalog_v3%rowtype;
begin
  if v_user_id is null then return jsonb_build_object('ok',false,'code','UNAUTHORIZED'); end if;
  if public.private_is_teacher_v3() then return jsonb_build_object('ok',false,'code','FORBIDDEN'); end if;
  if p_request_id is null or p_request_id !~* '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-5][0-9a-fA-F]{3}-[89ab][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$' then
    return jsonb_build_object('ok',false,'code','INVALID_REQUEST');
  end if;
  v_request_id := p_request_id::uuid;
  v_receipt := public.private_read_receipt_v3(v_request_id, 'accept_student_quest_v3');
  if v_receipt is not null then return v_receipt; end if;
  select * into v_core from public.player_core_v3 where user_id = v_user_id for update;
  if v_core.user_id is null then
    return public.private_store_receipt_v3(v_request_id,'accept_student_quest_v3',
      jsonb_build_object('ok',false,'code','CHARACTER_NOT_FOUND'));
  end if;
  if v_core.revision <> p_expected_revision then
    return public.private_store_receipt_v3(v_request_id,'accept_student_quest_v3',
      jsonb_build_object('ok',false,'code','REVISION_CONFLICT',
        'snapshot',public.private_build_student_snapshot_v3(v_user_id)));
  end if;
  select * into v_quest from public.game_quest_catalog_v3 where quest_id = p_quest_id;
  if v_quest.quest_id is null then
    return public.private_store_receipt_v3(v_request_id,'accept_student_quest_v3',
      jsonb_build_object('ok',false,'code','INVALID_QUEST'));
  end if;
  if exists (select 1 from public.player_quests_v3 where user_id=v_user_id and quest_id=p_quest_id)
    or (v_quest.sequence_number > 1 and not exists (
      select 1 from public.player_quests_v3 q
      join public.game_quest_catalog_v3 c on c.quest_id=q.quest_id
      where q.user_id=v_user_id
        and c.sequence_number = v_quest.sequence_number - 1
        and q.status = 'claimed'
    )) then
    return public.private_store_receipt_v3(v_request_id,'accept_student_quest_v3',
      jsonb_build_object('ok',false,'code','QUEST_LOCKED'));
  end if;
  insert into public.player_quests_v3(user_id,quest_id,status,progress,accepted_at)
  values(v_user_id,p_quest_id,'active',0,now());
  update public.player_core_v3 set
    gold=gold+v_quest.accept_gold,
    building=building+v_quest.accept_building,
    current_hp=case when p_quest_id='tut_healing_well' then 1 else current_hp end,
    revision=revision+1, updated_at=now()
  where user_id=v_user_id;
  if v_quest.accept_item_id is not null then
    insert into public.player_inventory_v3(
      user_id,item_definition_id,inventory_kind,enhancement_tier,equipped_slot,grant_source
    )
    select v_user_id,i.item_id,i.inventory_kind,0,null,'quest_accept'
    from public.game_item_catalog_v3 i where i.item_id=v_quest.accept_item_id
    on conflict do nothing;
  end if;
  if p_quest_id='tut_skill' and exists (
    select 1 from public.player_skills_v3 where user_id=v_user_id and rank>0
  ) then
    perform public.private_progress_student_quest_v3(v_user_id,'action','learnSkill');
  end if;
  v_response := jsonb_build_object('ok',true,'code','OK',
    'snapshot',public.private_build_student_snapshot_v3(v_user_id));
  return public.private_store_receipt_v3(v_request_id,'accept_student_quest_v3',v_response);
end;
$$;
create or replace function public.claim_student_quest_v3(
  p_quest_id text,
  p_expected_revision bigint,
  p_request_id text
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := auth.uid();
  v_request_id uuid;
  v_receipt jsonb;
  v_response jsonb;
  v_core public.player_core_v3%rowtype;
  v_quest public.game_quest_catalog_v3%rowtype;
  v_status text;
  v_new_exp integer;
  v_new_level integer;
begin
  if v_user_id is null then return jsonb_build_object('ok',false,'code','UNAUTHORIZED'); end if;
  if public.private_is_teacher_v3() then return jsonb_build_object('ok',false,'code','FORBIDDEN'); end if;
  if p_request_id is null or p_request_id !~* '^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[1-5][0-9a-fA-F]{3}-[89ab][0-9a-fA-F]{3}-[0-9a-fA-F]{12}$' then
    return jsonb_build_object('ok',false,'code','INVALID_REQUEST');
  end if;
  v_request_id := p_request_id::uuid;
  v_receipt := public.private_read_receipt_v3(v_request_id,'claim_student_quest_v3');
  if v_receipt is not null then return v_receipt; end if;
  select * into v_core from public.player_core_v3 where user_id=v_user_id for update;
  if v_core.user_id is null then return jsonb_build_object('ok',false,'code','CHARACTER_NOT_FOUND'); end if;
  if v_core.revision <> p_expected_revision then
    return public.private_store_receipt_v3(v_request_id,'claim_student_quest_v3',
      jsonb_build_object('ok',false,'code','REVISION_CONFLICT',
        'snapshot',public.private_build_student_snapshot_v3(v_user_id)));
  end if;
  select q.status into v_status
  from public.player_quests_v3 q
  where q.user_id=v_user_id and q.quest_id=p_quest_id for update;
  select * into v_quest
  from public.game_quest_catalog_v3
  where quest_id=p_quest_id;
  if v_status is null or v_status <> 'ready' then
    return public.private_store_receipt_v3(v_request_id,'claim_student_quest_v3',
      jsonb_build_object('ok',false,'code','QUEST_NOT_READY'));
  end if;
  v_new_exp := v_core.exp + v_quest.reward_exp;
  v_new_level := case when v_new_exp>=580 then 10 when v_new_exp>=470 then 9
    when v_new_exp>=370 then 8 when v_new_exp>=280 then 7 when v_new_exp>=200 then 6
    when v_new_exp>=130 then 5 when v_new_exp>=80 then 4 when v_new_exp>=40 then 3
    when v_new_exp>=10 then 2 else 1 end;
  v_new_level := greatest(v_core.level,least(10,v_new_level));
  update public.player_core_v3 set exp=v_new_exp,level=v_new_level,
    gold=gold+v_quest.reward_gold,building=building+v_quest.reward_building,
    max_hp=max_hp+(v_new_level-level)*2,
    current_hp=case when v_new_level>level then max_hp+(v_new_level-level)*2 else current_hp end,
    revision=revision+1,updated_at=now()
  where user_id=v_user_id;
  if v_quest.reward_item_id is not null then
    insert into public.player_inventory_v3(
      user_id,item_definition_id,inventory_kind,enhancement_tier,equipped_slot,grant_source
    )
    select v_user_id,i.item_id,i.inventory_kind,0,null,'quest_reward'
    from public.game_item_catalog_v3 i where i.item_id=v_quest.reward_item_id
    on conflict do nothing;
  end if;
  update public.player_quests_v3 set status='claimed',updated_at=now()
  where user_id=v_user_id and quest_id=p_quest_id;
  v_response:=jsonb_build_object('ok',true,'code','OK',
    'snapshot',public.private_build_student_snapshot_v3(v_user_id));
  return public.private_store_receipt_v3(v_request_id,'claim_student_quest_v3',v_response);
end;
$$;
